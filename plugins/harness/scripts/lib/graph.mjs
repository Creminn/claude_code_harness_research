export const PROJECT_NAME = 'claude-harness';
export const GRAPHITI_IMAGE_TAG = '1.1.0';
export const OLLAMA_IMAGE_TAG = '0.35.1';
export const EMBED_MODEL = 'nomic-embed-text';
export const DEFAULT_LLM = {
  anthropic: 'claude-haiku-4-5',
  openai: 'gpt-5-mini',
  local: 'qwen2.5:7b',
};

export const ENTITY_TYPES = [
  ['Decision', 'A choice made for the project, with its reason. Includes which earlier decision it replaces, if any.'],
  ['Constraint', 'A rule or limit the project must respect: technical, legal, performance, compatibility or team policy.'],
  ['Component', 'A significant module, service, package, API or data store of the project (not individual functions).'],
  ['Task', 'A piece of work that is planned, in progress, blocked or done, with its status.'],
  ['Bug', 'A defect: its symptom, root cause and the change that fixed it.'],
  ['FailedAttempt', 'An approach that was tried and did not work, and why, so it is not repeated.'],
  ['Convention', 'An agreed way of doing things in this codebase: naming, structure, tooling, workflow.'],
  ['OpenQuestion', 'An unresolved question or uncertainty that still needs an answer.'],
];

const q = (v) => JSON.stringify(String(v));

// Where Ollama runs: a sidecar container, or the host's own Ollama (faster on a Mac).
function ollamaBase(config) {
  return config.ollama === 'host' ? 'http://host.docker.internal:11434/v1' : 'http://ollama:11434/v1';
}

export function usesOllama(config) {
  return config.graphMode === 'anthropic' || config.graphMode === 'local';
}

export function embedderId(config) {
  return config.graphMode === 'openai' ? 'openai-1536' : 'nomic-768';
}

export function renderGraphitiConfig(config) {
  const mode = config.graphMode;
  const model = config.llmModel || DEFAULT_LLM[mode];
  const lines = [
    '# Generated by claude-harness. Edits are overwritten by "harness graph setup" and "graph up".',
    'server:',
    '  transport: "http"',
    '  host: "0.0.0.0"',
    '  port: 8000',
    'llm:',
  ];
  if (mode === 'anthropic') {
    lines.push(
      '  provider: "anthropic"',
      `  model: ${q(model)}`,
      '  max_tokens: 4096',
      '  providers:',
      '    anthropic:',
      '      api_key: ${ANTHROPIC_API_KEY}',
      '      max_retries: 3',
    );
  } else if (mode === 'openai') {
    lines.push(
      '  provider: "openai"',
      `  model: ${q(model)}`,
      '  max_tokens: 4096',
      '  providers:',
      '    openai:',
      '      api_key: ${OPENAI_API_KEY}',
      '      api_url: "https://api.openai.com/v1"',
    );
  } else if (mode === 'local') {
    lines.push(
      '  provider: "openai"',
      `  model: ${q(model)}`,
      '  max_tokens: 4096',
      '  structured_output_mode: "json_object"',
      '  providers:',
      '    openai:',
      '      api_key: "ollama"',
      `      api_url: ${q(ollamaBase(config))}`,
    );
  } else {
    throw new Error(`Unknown graph mode "${mode}"`);
  }
  lines.push('embedder:', '  provider: "openai"');
  if (mode === 'openai') {
    lines.push(
      '  model: "text-embedding-3-small"',
      '  dimensions: 1536',
      '  providers:',
      '    openai:',
      '      api_key: ${OPENAI_API_KEY}',
      '      api_url: "https://api.openai.com/v1"',
    );
  } else {
    lines.push(
      `  model: ${q(EMBED_MODEL)}`,
      '  dimensions: 768',
      '  providers:',
      '    openai:',
      '      api_key: "ollama"',
      `      api_url: ${q(ollamaBase(config))}`,
    );
  }
  lines.push(
    'database:',
    '  provider: "falkordb"',
    '  providers:',
    '    falkordb:',
    '      uri: "redis://localhost:6379"',
    '      password: ${FALKORDB_PASSWORD:}',
    '      database: "default_db"',
    'graphiti:',
    '  group_id: "main"',
    '  user_id: "claude-harness"',
    '  entity_types:',
  );
  for (const [name, description] of ENTITY_TYPES) {
    lines.push(`    - name: ${q(name)}`, `      description: ${q(description)}`);
  }
  return `${lines.join('\n')}\n`;
}

// Values in .env are read by docker compose for interpolation and passed to the container.
export function parseEnv(text) {
  const env = {};
  for (const line of String(text || '').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Za-z_][A-Za-z0-9_]*)\s*=\s*(.*)\s*$/);
    if (!m) continue;
    let v = m[2];
    if (/^".*"$/.test(v) || /^'.*'$/.test(v)) v = v.slice(1, -1);
    env[m[1]] = v;
  }
  return env;
}

export function readGraphEnv() {
  try { return parseEnv(readFileSync(paths.graphEnv(), 'utf8')); } catch { return {}; }
}

export function renderEnv(config, secrets) {
  const env = {
    HARNESS_EMBEDDER: embedderId(config),
    HARNESS_MCP_PORT: String(config.mcpPort),
    HARNESS_UI_PORT: String(config.uiPort),
    GRAPHITI_IMAGE_TAG,
    OLLAMA_IMAGE_TAG,
  };
  if (usesOllama(config)) env.OPENAI_BASE_URL = ollamaBase(config);
  if (secrets.ANTHROPIC_API_KEY) env.ANTHROPIC_API_KEY = secrets.ANTHROPIC_API_KEY;
  if (secrets.OPENAI_API_KEY) env.OPENAI_API_KEY = secrets.OPENAI_API_KEY;
  const body = Object.entries(env).map(([k, v]) => `${k}=${String(v).replace(/[\r\n]/g, '')}`).join('\n');
  return `# Generated by claude-harness. Contains API keys: keep private.\n${body}\n`;
}

export function writeGraphFiles(config, secrets = readGraphEnv()) {
  const dir = ensureDir(paths.graphDir(), 0o700);
  copyFileSync(join(PLUGIN_ROOT, 'graph', 'compose.yml'), join(dir, 'compose.yml'));
  copyFileSync(join(PLUGIN_ROOT, 'graph', 'compose.ui.yml'), join(dir, 'compose.ui.yml'));
  ensureDir(join(dir, 'patches'));
  copyFileSync(join(PLUGIN_ROOT, 'graph', 'patches', 'sitecustomize.py'), join(dir, 'patches', 'sitecustomize.py'));
  writeFileAtomic(join(dir, 'config.yaml'), renderGraphitiConfig(config));
  writeFileAtomic(paths.graphEnv(), renderEnv(config, secrets), { mode: 0o600 });
}

export function missingSecret(config, secrets = readGraphEnv()) {
  if (config.graphMode === 'anthropic' && !secrets.ANTHROPIC_API_KEY) return 'ANTHROPIC_API_KEY';
  if (config.graphMode === 'openai' && !secrets.OPENAI_API_KEY) return 'OPENAI_API_KEY';
  return null;
}

export function dockerStatus() {
  const run = (args) => spawnSync('docker', args, { encoding: 'utf8', timeout: 15000, windowsHide: true });
  const version = run(['version', '--format', '{{.Server.Version}}']);
  if (version.error) return { installed: false, running: false, compose: false };
  const running = version.status === 0 && Boolean(version.stdout.trim());
  const compose = run(['compose', 'version', '--short']);
  return {
    installed: true,
    running,
    serverVersion: running ? version.stdout.trim() : null,
    compose: compose.status === 0,
    composeVersion: compose.status === 0 ? compose.stdout.trim() : null,
  };
}

function composeArgs(config, { ui = false } = {}) {
  const dir = paths.graphDir();
  const args = ['compose', '--project-name', PROJECT_NAME, '--project-directory', dir, '--env-file', paths.graphEnv(), '-f', join(dir, 'compose.yml')];
  if (ui) args.push('-f', join(dir, 'compose.ui.yml'));
  if (usesOllama(config) && config.ollama !== 'host') args.push('--profile', 'ollama');
  return args;
}

function docker(args, { quiet = false } = {}) {
  const res = spawnSync('docker', args, { stdio: quiet ? 'pipe' : 'inherit', encoding: 'utf8', windowsHide: true });
  if (res.error) throw res.error;
  if (res.status !== 0) {
    const detail = quiet ? `${res.stderr || ''}`.trim().slice(-500) : '';
    throw new Error(`docker ${args.slice(0, 6).join(' ')} ... failed (exit ${res.status}) ${detail}`);
  }
  return res.stdout;
}

async function waitFor(check, timeoutMs, onWait) {
  const start = Date.now();
  while (Date.now() - start < timeoutMs) {
    if (await check()) return true;
    onWait?.();
    await new Promise((r) => setTimeout(r, 3000));
  }
  return false;
}

async function pullOllamaModels(config, say) {
  const models = [EMBED_MODEL];
  if (config.graphMode === 'local') models.push(config.llmModel || DEFAULT_LLM.local);
  for (const model of models) {
    say(`Pulling Ollama model ${model} (first time only) ...`);
    if (config.ollama === 'host') {
      let res;
      try {
        res = await fetch('http://127.0.0.1:11434/api/pull', {
          method: 'POST',
          body: JSON.stringify({ model, stream: false }),
          signal: AbortSignal.timeout(30 * 60 * 1000),
        });
      } catch {
        throw new Error('Ollama is not running on this machine (http://127.0.0.1:11434). Start it, or run "harness graph setup --ollama sidecar" to use a container instead.');
      }
      if (!res.ok) throw new Error(`Host Ollama could not pull ${model}: HTTP ${res.status}`);
    } else {
      await waitFor(async () => spawnSync('docker', [...composeArgs(config), 'exec', '-T', 'ollama', 'ollama', 'list'], { stdio: 'ignore', windowsHide: true }).status === 0, 60000);
      docker([...composeArgs(config), 'exec', '-T', 'ollama', 'ollama', 'pull', model]);
    }
  }
}

export async function graphUp({ ui = false, say = console.log } = {}) {
  const config = loadConfig();
  if (config.graphMode === 'off') throw new Error('The knowledge graph is off. Run "harness graph setup" first.');
  const missing = missingSecret(config);
  if (missing) throw new Error(`${missing} is not set. Run "harness graph setup" in a terminal to add it.`);
  const d = dockerStatus();
  if (!d.installed) throw new Error('Docker is not installed. Install Docker Desktop (Mac/Windows) or Docker Engine (Linux), then run "harness graph up".');
  if (!d.running) throw new Error('Docker is installed but not running. Start Docker, then run "harness graph up".');
  if (!d.compose) throw new Error('Docker Compose v2 is missing ("docker compose version" failed).');

  const release = tryLock('graph-up', { staleMs: 30 * 60 * 1000 });
  if (!release) throw new Error('Another "graph up" is already running.');
  try {
    writeGraphFiles(config);
    writeGraphStatus('starting', 'Starting the knowledge graph containers');
    say('Starting the knowledge graph (the first start downloads the images, which can take a few minutes) ...');
    docker([...composeArgs(config, { ui }), 'up', '-d', '--remove-orphans']);
    if (usesOllama(config)) await pullOllamaModels(config, say);
    say('Waiting for the graph server to become healthy ...');
    const ok = await waitFor(() => graphHealth(config, 2000), 4 * 60 * 1000);
    if (!ok) {
      writeGraphStatus('down', 'The graph server did not become healthy. Run "harness graph logs".');
      throw new Error('The graph server did not become healthy within 4 minutes. Run "harness graph logs" to see why.');
    }
    writeGraphStatus('healthy');
    return true;
  } finally {
    release();
  }
}

export function graphDown({ purge = false } = {}) {
  const config = loadConfig();
  if (!existsSync(join(paths.graphDir(), 'compose.yml'))) return false;
  const args = [...composeArgs({ ...config, graphMode: config.graphMode === 'off' ? 'anthropic' : config.graphMode }), 'down'];
  if (purge) args.push('--volumes');
  docker(args);
  writeGraphStatus(config.graphMode === 'off' ? 'off' : 'down', 'Stopped');
  return true;
}

export function graphLogs(lines = 200) {
  const config = loadConfig();
  docker([...composeArgs(config), 'logs', '--tail', String(lines), 'graphiti']);
}

export function graphUiUrl(config = loadConfig()) {
  return `http://127.0.0.1:${config.uiPort}`;
}

export async function detectHostOllama() {
  try {
    const res = await fetch('http://127.0.0.1:11434/api/version', { signal: AbortSignal.timeout(1500) });
    return res.ok;
  } catch {
    return false;
  }
}

export function execQuiet(cmd, args) {
  try {
    return execFileSync(cmd, args, { encoding: 'utf8', stdio: ['ignore', 'pipe', 'ignore'], timeout: 10000, windowsHide: true }).trim();
  } catch {
    return null;
  }
}
